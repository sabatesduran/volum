const dictionaries: Record<Exclude<AppLanguage, "en">, Record<string, string>> = { ca, es };

export function resolveLanguage(language?: string): AppLanguage {
  const code = language?.trim().toLocaleLowerCase().split(/[-_]/)[0];
  return code === "ca" || code === "es" || code === "en" ? code : "en";
}

export function resolveLanguagePreference(preference: LanguagePreference, systemLanguage?: string): AppLanguage {
  return preference === "system" ? resolveLanguage(systemLanguage ?? (typeof navigator === "undefined" ? undefined : navigator.language)) : preference;
}

export let appLanguage = resolveLanguage(typeof navigator === "undefined" ? undefined : navigator.language);
export function localeForLanguage(language: AppLanguage): string {
  return language === "ca" ? "ca-ES" : language === "es" ? "es-ES" : "en";
}

export let intlLocale = localeForLanguage(appLanguage);

export function setAppLanguage(language: AppLanguage): void {
  appLanguage = language;
  intlLocale = localeForLanguage(language);
  initializeDocumentLanguage();
}

export function translate(source: string, language: AppLanguage, replacements: Replacements = {}): string {
  const translated = language === "en" ? source : dictionaries[language][source] ?? source;
  return Object.entries(replacements).reduce(
    (output, [key, value]) => output.replaceAll(`{${key}}`, String(value)),
    translated
  );
}

export function t(source: string, replacements: Replacements = {}): string {
  return translate(source, appLanguage, replacements);
}

export function plural(count: number, singular: string, other: string, replacements: Replacements = {}): string {
  return t(count === 1 ? singular : other, { count, ...replacements });
}

export function initializeDocumentLanguage(): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = appLanguage;
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("A beautiful home for your 3D models."));
}
