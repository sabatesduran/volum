import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(appRoot, "../..");
const registryPath = join(appRoot, "locales.json");
const generatedRegistryPath = join(appRoot, "src/locales/generated.ts");
const defaultMessagesPath = join(appRoot, "src/locales/en.json");
const nativeKeys = [
  "NSCameraUsageDescription",
  "NSPhotoLibraryUsageDescription",
  "NSLocalNetworkUsageDescription",
];
const xmlStart = "<!-- BEGIN GENERATED MOBILE LOCALES -->";
const xmlEnd = "<!-- END GENERATED MOBILE LOCALES -->";
const yamlStart = "# BEGIN GENERATED MOBILE LOCALES";
const yamlEnd = "# END GENERATED MOBILE LOCALES";

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function write(path, value) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, value);
}

function canonicalTag(value) {
  try {
    return new Intl.Locale(value).toString();
  } catch {
    throw new Error(`Invalid BCP-47 locale: ${value}`);
  }
}

function loadRegistry() {
  const registry = readJson(registryPath);
  if (!Array.isArray(registry.languages) || !registry.languages.length) throw new Error("locales.json has no languages");
  const codes = new Set();
  for (const language of registry.languages) {
    for (const key of ["code", "locale", "intl", "ios", "android", "store", "capture", "nativeName", "direction"]) {
      if (!language[key]) throw new Error(`Language ${language.code ?? "<unknown>"} is missing ${key}`);
    }
    if (codes.has(language.code)) throw new Error(`Duplicate language code: ${language.code}`);
    codes.add(language.code);
    canonicalTag(language.locale);
    canonicalTag(language.intl);
    canonicalTag(language.android);
    if (!Array.isArray(language.aliases)) language.aliases = [];
    if (language.direction !== "ltr" && language.direction !== "rtl") throw new Error(`Invalid direction for ${language.code}`);
  }
  if (!codes.has(registry.default)) throw new Error(`Default language ${registry.default} is not registered`);
  return registry;
}

function generatedRegistry(registry) {
  const entries = registry.languages.map((language) => `  ${JSON.stringify(language)},`).join("\n");
  return `// Generated by scripts/locales.mjs. Edit apps/mobile/locales.json instead.\nexport const DEFAULT_LANGUAGE = ${JSON.stringify(registry.default)} as const;\nexport const MOBILE_LANGUAGES = [\n${entries}\n] as const;\n\nexport type MobileLanguageDefinition = (typeof MOBILE_LANGUAGES)[number];\nexport type AppLanguage = MobileLanguageDefinition["code"];\n`;
}

function xmlLocaleBlock(registry, indent = "  ") {
  const values = registry.languages.map((language) => `${indent}  <string>${language.ios}</string>`).join("\n");
  return `${indent}${xmlStart}\n${indent}<key>CFBundleLocalizations</key>\n${indent}<array>\n${values}\n${indent}</array>\n${indent}${xmlEnd}`;
}

function replaceXmlLocaleBlock(source, registry, indent = "  ") {
  const block = xmlLocaleBlock(registry, indent);
  const marked = new RegExp(`${escapeRegExp(indent + xmlStart)}[\\s\\S]*?${escapeRegExp(indent + xmlEnd)}`);
  if (marked.test(source)) return source.replace(marked, block);
  const existing = new RegExp(`${escapeRegExp(indent)}<key>CFBundleLocalizations</key>\\s*<array>[\\s\\S]*?</array>\\s*`);
  if (existing.test(source)) return source.replace(existing, `${block}\n`);
  const closing = `${indent}</dict>`;
  const closingIndex = source.lastIndexOf(closing);
  if (closingIndex < 0) throw new Error("Info.plist has no root dictionary closing tag");
  return `${source.slice(0, closingIndex)}${block}\n${source.slice(closingIndex)}`;
}

function replaceYamlLocaleBlock(source, registry) {
  const indent = "        ";
  const block = `${indent}${yamlStart}\n${indent}CFBundleLocalizations: [${registry.languages.map((language) => language.ios).join(", ")}]\n${indent}${yamlEnd}`;
  const marked = new RegExp(`${escapeRegExp(indent + yamlStart)}[\\s\\S]*?${escapeRegExp(indent + yamlEnd)}`);
  if (marked.test(source)) return source.replace(marked, block);
  return source.replace(`${indent}LSRequiresIPhoneOS:`, `${block}\n${indent}LSRequiresIPhoneOS:`);
}

function androidLocaleConfig(registry) {
  const locales = registry.languages.map((language) => `    <locale android:name="${language.android}" />`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by apps/mobile/scripts/locales.mjs. -->\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n${locales}\n</locale-config>\n`;
}

function withAndroidLocaleConfig(source) {
  if (source.includes("android:localeConfig=")) return source;
  return source.replace("        android:label=\"@string/app_name\"", "        android:label=\"@string/app_name\"\n        android:localeConfig=\"@xml/locales_config\"");
}

function infoPlistStrings(values) {
  return `${nativeKeys.map((key) => `"${key}" = "${escapeStringsValue(values[key])}";`).join("\n")}\n`;
}

function escapeStringsValue(value) {
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("\n", "\\n");
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function expectedOutputs(registry) {
  const outputs = new Map([[generatedRegistryPath, generatedRegistry(registry)]]);
  const sourcePlist = join(appRoot, "src-tauri/Info.ios.plist");
  outputs.set(sourcePlist, replaceXmlLocaleBlock(readFileSync(sourcePlist, "utf8"), registry, "  "));
  const generatedPlist = join(appRoot, "src-tauri/gen/apple/volum-companion_iOS/Info.plist");
  if (existsSync(generatedPlist)) outputs.set(generatedPlist, replaceXmlLocaleBlock(readFileSync(generatedPlist, "utf8"), registry, "\t"));
  const projectYaml = join(appRoot, "src-tauri/gen/apple/project.yml");
  if (existsSync(projectYaml)) outputs.set(projectYaml, replaceYamlLocaleBlock(readFileSync(projectYaml, "utf8"), registry));
  const androidConfig = join(appRoot, "src-tauri/gen/android/app/src/main/res/xml/locales_config.xml");
  outputs.set(androidConfig, androidLocaleConfig(registry));
  const androidManifest = join(appRoot, "src-tauri/gen/android/app/src/main/AndroidManifest.xml");
  outputs.set(androidManifest, withAndroidLocaleConfig(readFileSync(androidManifest, "utf8")));
  for (const language of registry.languages) {
    const nativePath = join(appRoot, `src/locales/native/${language.code}.json`);
    const native = readJson(nativePath);
    outputs.set(
      join(appRoot, `src-tauri/gen/apple/volum-companion_iOS/${language.ios}.lproj/InfoPlist.strings`),
      infoPlistStrings(native),
    );
  }
  return outputs;
}

function validateTranslations(registry) {
  const base = readJson(defaultMessagesPath);
  const baseKeys = Object.keys(base).sort();
  const failures = [];
  for (const language of registry.languages) {
    const path = join(appRoot, `src/locales/${language.code}.json`);
    if (!existsSync(path)) {
      failures.push(`Missing ${path}`);
      continue;
    }
    const messages = readJson(path);
    const keys = Object.keys(messages).sort();
    const missing = baseKeys.filter((key) => !keys.includes(key));
    const extra = keys.filter((key) => !baseKeys.includes(key));
    if (missing.length) failures.push(`${language.code} is missing ${missing.length} messages: ${missing.slice(0, 5).join(", ")}`);
    if (extra.length) failures.push(`${language.code} has ${extra.length} unknown messages: ${extra.slice(0, 5).join(", ")}`);
    for (const key of baseKeys) {
      if (!String(messages[key] ?? "").trim()) failures.push(`${language.code} has an empty translation for ${key}`);
      const expected = placeholders(base[key]);
      const actual = placeholders(messages[key] ?? "");
      if (expected.join("|") !== actual.join("|")) failures.push(`${language.code} has different placeholders for ${key}`);
    }
    validateLocaleAssets(language, failures);
  }
  if (failures.length) throw new Error(failures.slice(0, 20).join("\n"));
}

function validateLocaleAssets(language, failures) {
  const nativePath = join(appRoot, `src/locales/native/${language.code}.json`);
  if (!existsSync(nativePath)) failures.push(`Missing ${nativePath}`);
  else {
    const native = readJson(nativePath);
    for (const key of nativeKeys) if (!String(native[key] ?? "").trim()) failures.push(`${nativePath} is missing ${key}`);
  }
  const goldiePath = join(appRoot, `goldie/locales/${language.code}.json`);
  if (!existsSync(goldiePath)) failures.push(`Missing ${goldiePath}`);
  else if (JSON.stringify(readJson(goldiePath)).includes('""')) failures.push(`${goldiePath} contains empty screenshot copy`);
  const appInfo = join(repoRoot, `metadata/app-info/${language.store}.json`);
  if (!existsSync(appInfo)) failures.push(`Missing ${appInfo}`);
  for (const version of metadataVersions()) {
    const versionMetadata = join(repoRoot, `metadata/version/${version}/${language.store}.json`);
    if (!existsSync(versionMetadata)) failures.push(`Missing ${versionMetadata}`);
  }
}

function placeholders(value) {
  return [...String(value).matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]).sort();
}

function metadataVersions() {
  const root = join(repoRoot, "metadata/version");
  return existsSync(root) ? readdirSync(root, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name) : [];
}

function sync(registry) {
  validateTranslations(registry);
  for (const [path, content] of expectedOutputs(registry)) write(path, content);
  console.log(`Synchronized ${registry.languages.length} mobile languages.`);
}

function check(registry) {
  validateTranslations(registry);
  const stale = [];
  for (const [path, content] of expectedOutputs(registry)) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) stale.push(path);
  }
  if (stale.length) throw new Error(`Generated locale files are stale. Run npm run locales:sync.\n${stale.join("\n")}`);
  const project = join(appRoot, "src-tauri/gen/apple/volum-companion.xcodeproj/project.pbxproj");
  if (existsSync(project)) {
    const source = readFileSync(project, "utf8");
    const missing = registry.languages.filter((language) => !source.includes(`${language.ios}.lproj`));
    if (missing.length) throw new Error(`Xcode locale resources are stale. Run npm run locales:xcode. Missing: ${missing.map((value) => value.ios).join(", ")}`);
  }
  console.log(`Validated ${registry.languages.length} mobile languages.`);
}

function add(registry, requestedTag) {
  if (!requestedTag) throw new Error("Usage: npm run locale:add -- <BCP-47 locale, for example fr-FR>");
  const locale = canonicalTag(requestedTag);
  const base = new Intl.Locale(locale).language;
  if (registry.languages.some((language) => [language.code, language.locale, language.intl, ...language.aliases].some((value) => canonicalTag(value).toLocaleLowerCase() === locale.toLocaleLowerCase()))) {
    throw new Error(`${locale} is already registered`);
  }
  const code = registry.languages.some((language) => language.code === base) ? locale : base;
  const rtl = new Set(["ar", "dv", "fa", "he", "ku", "ps", "sd", "ug", "ur", "yi"]).has(base);
  const nativeName = new Intl.DisplayNames([locale], { type: "language" }).of(locale) ?? locale;
  const language = {
    code,
    locale,
    intl: locale,
    ios: locale,
    android: locale,
    store: locale,
    capture: locale,
    nativeName: nativeName[0].toLocaleUpperCase(locale) + nativeName.slice(1),
    direction: rtl ? "rtl" : "ltr",
    aliases: base === locale ? [] : [base],
  };
  registry.languages.push(language);
  write(registryPath, `${JSON.stringify(registry, null, 2)}\n`);
  const baseMessages = readJson(defaultMessagesPath);
  write(join(appRoot, `src/locales/${code}.json`), `${JSON.stringify(Object.fromEntries(Object.keys(baseMessages).map((key) => [key, ""])), null, 2)}\n`);
  write(join(appRoot, `src/locales/native/${code}.json`), `${JSON.stringify(Object.fromEntries(nativeKeys.map((key) => [key, ""])), null, 2)}\n`);
  const goldie = readJson(join(appRoot, "goldie/locales/en.json"));
  const blankGoldie = JSON.parse(JSON.stringify(goldie, (_key, value) => typeof value === "string" ? "" : value));
  write(join(appRoot, `goldie/locales/${code}.json`), `${JSON.stringify(blankGoldie, null, 2)}\n`);
  scaffoldMetadata(language);
  for (const [path, content] of expectedOutputs(registry)) write(path, content);
  runXcodegen();
  console.log(`Added ${locale}. Translate the generated ${code} files, then run npm run locales:check.`);
}

function scaffoldMetadata(language) {
  const appInfo = readJson(join(repoRoot, "metadata/app-info/en-US.json"));
  write(join(repoRoot, `metadata/app-info/${language.store}.json`), `${JSON.stringify({ ...appInfo, name: "", subtitle: "" }, null, 2)}\n`);
  for (const version of metadataVersions()) {
    const metadata = readJson(join(repoRoot, `metadata/version/${version}/en-US.json`));
    write(join(repoRoot, `metadata/version/${version}/${language.store}.json`), `${JSON.stringify({ ...metadata, description: "", keywords: "", promotionalText: "" }, null, 2)}\n`);
  }
}

function runXcodegen() {
  const appleRoot = join(appRoot, "src-tauri/gen/apple");
  try {
    execFileSync("xcodegen", ["generate", "--spec", "project.yml"], { cwd: appleRoot, stdio: "inherit" });
  } catch (error) {
    if (process.platform === "darwin") throw error;
    console.warn("xcodegen is unavailable on this platform; regenerate the checked-in Xcode project on macOS.");
  }
}

const command = process.argv[2] ?? "sync";
const registry = loadRegistry();
if (command === "sync") sync(registry);
else if (command === "check") check(registry);
else if (command === "add") add(registry, process.argv[3]);
else if (command === "xcode") runXcodegen();
else throw new Error(`Unknown locale command: ${command}`);
